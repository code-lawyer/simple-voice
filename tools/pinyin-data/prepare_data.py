"""Deterministic data-only conversion for the frozen 2026-11-15 selection.

No Wanxiang executable code or Rime-Ice files are used. CLI orchestration,
provenance verification and ESDB construction live in pipeline.py.
"""

from collections import Counter
import json
from pathlib import Path
import re
import sqlite3
import unicodedata

TOOLS = Path(__file__).resolve().parent


def write_crlf(path: Path, text: str) -> None:
    """Preserve the research artifact's CRLF bytes on every host OS."""
    path.write_bytes(text.replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8"))


def plain_pinyin(code: str) -> str:
    for char in "üǖǘǚǜ":
        code = code.replace(char, "v")
    code = "".join(
        char for char in unicodedata.normalize("NFD", code)
        if not unicodedata.combining(char)
    ).lower()
    return " ".join(code.split())


def read_wanxiang(path: Path) -> dict:
    entries = {}
    with path.open(encoding="utf-8") as source:
        for line in source:
            fields = line.rstrip("\r\n").split("\t")
            if len(fields) != 3 or not fields[2].isdigit():
                continue
            text, code, weight = fields[0], plain_pinyin(fields[1]), int(fields[2])
            if weight <= 0 or not re.fullmatch(r"[a-z]+(?: [a-z]+)*", code):
                continue
            key = text, code
            entries[key] = max(entries.get(key, 0), weight)
    return entries


def write_dictionary(output: Path, name: str, entries: dict, extra: str = "") -> None:
    header = (
        "# Generated by prepare_data.py; see DATA-SOURCES.md\n---\n"
        f'name: {name}\nversion: "2026-11-15"\nsort: by_weight\n'
        f"use_preset_vocabulary: false\n{extra}...\n"
    )
    rows = "".join(
        f"{text}\t{code}\t{weight}\n"
        for (text, code), weight in sorted(entries.items(), key=lambda item: (item[0][1], item[0][0]))
    )
    write_crlf(output / (name + ".dict.yaml"), header + rows)


def generate(source_dir: Path, database: Path, output: Path) -> dict:
    policy = json.loads((TOOLS / "selection.json").read_text(encoding="utf-8"))
    essential = set(policy["essential_chinese"])
    wx = source_dir / "wanxiang/dicts"
    chars = read_wanxiang(wx / "zi.dict.yaml")
    words = read_wanxiang(wx / "jichu.dict.yaml")
    eligible = {key: weight for key, weight in words.items() if 2 <= len(key[0]) <= 8}
    core = dict(sorted(eligible.items(), key=lambda item: (-item[1], item[0]))[
        :policy["initial_chinese_core_limit"]
    ])
    essential_added = 0
    for key, weight in words.items():
        if key[0] in essential and key not in core:
            core[key] = weight
            essential_added += 1
    selected_text = {text for text, _ in core}
    for key, weight in read_wanxiang(wx / "duoyin.dict.yaml").items():
        if key[0] in selected_text:
            core[key] = max(core.get(key, 0), weight)

    baseline = set()
    for line in (source_dir / "pinyin-simp/pinyin_simp.dict.yaml").read_text(encoding="utf-8").splitlines():
        row = line.split("\t")
        if len(row) == 3:
            baseline.add((row[0], row[1]))
    before_gate = len(core)
    core = {
        key: weight for key, weight in core.items()
        if len(key[0]) <= 2 or weight >= policy["long_entry_min_weight"]
        or key in baseline or key[0] in essential
    }
    write_dictionary(output, "voiceime_chars", chars)
    write_dictionary(output, "voiceime_core", core)
    write_dictionary(output, "voiceime", {}, "import_tables:\n  - voiceime_chars\n  - voiceime_core\n")

    conn = sqlite3.connect(database.resolve().as_uri() + "?mode=ro", uri=True)
    try:
        rows = conn.execute("""select word,min(size) from scowl_v0
            where size<=60 and variant_level<=1 and spelling in ('_','A')
            and region in ('','US') and base_pos not in ('abbr') and category=''
            group by word""").fetchall()
    finally:
        conn.close()
    english = {}
    levels = Counter()
    for text, size in rows:
        if size > 50 and " " not in text:
            continue
        if not re.fullmatch(r"[A-Za-z]+(?:[ '-][A-Za-z]+)*", text):
            continue
        if not 3 <= len(text) <= 40 or text.endswith("'s"):
            continue
        code = re.sub(r"[ '-]", "", text).lower()
        if len(code) < 3:
            continue
        weight = max(50, 1000 - (int(size) - 10) * 15)
        english[text, code] = max(english.get((text, code), 0), weight)
        levels[int(size)] += 1
    for text in policy["authored_english"]:
        code = re.sub(r"[^a-z]", "", text.lower())
        for key in [key for key in english if key[1] == code]:
            del english[key]
        english[text, code] = 1500
    lowercase_rows = len(english)
    for (text, code), weight in list(english.items()):
        canonical = re.sub(r"[ '-]", "", text)
        if canonical != code:
            english[text, canonical] = weight
    write_dictionary(output, "voiceime_english", english)
    mixed = {(text, code): weight for text, code, weight in policy["authored_mixed"]}
    write_dictionary(output, "voiceime_mixed", mixed)
    return {
        "chinese_character_rows": len(chars), "source_chinese_word_rows": len(words),
        "chinese_core_before_long_entry_gate": before_gate, "chinese_core_rows": len(core),
        "long_entries_removed": before_gate - len(core), "essential_added": essential_added,
        "english_lowercase_rows": lowercase_rows, "english_code_rows": len(english),
        "esdb_size_classes": dict(sorted(levels.items())),
        "authored_english_terms": len(policy["authored_english"]), "mixed_code_rows": len(mixed),
    }
